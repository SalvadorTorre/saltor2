// npm install --prefix tmp/ncf-db @electric-sql/pglite; node scripts/tests/proforma.test.mjs
import { PGlite } from '../../tmp/ncf-db/node_modules/@electric-sql/pglite/dist/index.js';
import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const db = new PGlite();
await db.exec(`
create role anon; create role authenticated; create role service_role bypassrls;
create schema myappdb; create schema private; create schema auth;
create function auth.uid() returns uuid language sql as $$ select '00000000-0000-0000-0000-000000000001'::uuid $$;
create function private.current_empresa_id() returns integer language sql as $$ select nullif(current_setting('request.company',true),'')::integer $$;
create function private.es_dueno_sistema() returns boolean language sql as $$ select coalesce(current_setting('request.owner',true),'false')='true' $$;
create function private.ncf_numero_rango(text,text) returns bigint language sql as $$ select $1::bigint $$;
grant usage on schema myappdb,private,auth to authenticated;
grant execute on all functions in schema private,auth to authenticated;
create table myappdb.empresas(id integer primary key);
insert into myappdb.empresas values(1),(2);
create table myappdb.ncf_secuencias(id integer primary key,empresa_id integer,tipo_ncf text,serie text,rango_inicial text,usados integer);
insert into myappdb.ncf_secuencias values(1,1,'332','E332','1',7);
`);
await db.exec(await readFile('supabase/migrations/20261016230000_company_proforma_e332.sql','utf8'));
let passed=0;
const check=(ok,label)=>{assert.ok(ok,label);console.log('PASS',label);passed++;};
const q=async(sql,args)=>(await db.query(sql,args)).rows;
const rejects=async(sql,pattern,label,args)=>{await assert.rejects(()=>db.query(sql,args),pattern);console.log('PASS',label);passed++;};
let seed=(await q('select * from myappdb.empresas_proforma'))[0];
check(seed.activa===false && Number(seed.ultimo_numero)===7,'migra contador anterior sin habilitar empresas');
await db.exec("set role authenticated; set request.company='1'; set request.owner='false';");
await rejects('select myappdb.plataforma_configurar_proforma(1,true)',/dueño/,'un tenant no puede activar la función');
await rejects("update myappdb.empresas_proforma set activa=true",/permission denied/,'no se activa por escritura directa');
await db.exec("set request.owner='true';");
let settings=(await q('select myappdb.plataforma_configurar_proforma(1,true) as config'))[0].config;
await q('select myappdb.plataforma_configurar_proforma(2,true)');
check((await q('select * from myappdb.empresas_proforma')).length===2,'dueño configura cada empresa');
await db.exec("set request.owner='false';");
check((await q('select * from myappdb.empresas_proforma')).length===1,'tenant ve solo su configuración');
const adjust='select myappdb.ajustar_contador_proforma($1,$2,$3) as config';
settings=(await q(adjust,[100,settings.ultimo_numero,settings.actualizado_en]))[0].config;
check(Number(settings.ultimo_numero)===100,'contador avanza sin autorización ni vencimiento');
const stale={...settings};
settings=(await q(adjust,[5,settings.ultimo_numero,settings.actualizado_en]))[0].config;
check(Number(settings.ultimo_numero)===5,'permite corregir el contador hacia atrás');
await rejects(adjust,/cambió/,'rechaza ajustes con versión obsoleta',[110,stale.ultimo_numero,stale.actualizado_en]);
await rejects('select myappdb.ajustar_contador_proforma($1,$2,$3,2)',/dueño/,'tenant no puede ajustar otra empresa',[20,0,settings.actualizado_en]);
await rejects(adjust,/entre 0/,'rechaza fuera de límite',[100000000000,settings.ultimo_numero,settings.actualizado_en]);
await rejects(adjust,/entre 0/,'rechaza contador negativo',[-1,settings.ultimo_numero,settings.actualizado_en]);
check((await q("select * from myappdb.empresas_proforma_historial where accion='Contador ajustado'")).length===2,'conserva cada ajuste en historial');
await rejects('delete from myappdb.empresas_proforma_historial',/permission denied/,'historial no editable por tenant');
await db.exec("set request.owner='true';");
settings=(await q('select myappdb.plataforma_configurar_proforma(1,false) as config'))[0].config;
check(Number(settings.ultimo_numero)===5,'desactivar conserva el contador');
await db.exec("set request.owner='false';");
await rejects(adjust,/no está activa/,'desactivada no permite ajustes',[30,settings.ultimo_numero,settings.actualizado_en]);
await db.exec("set request.owner='true';");
settings=(await q('select myappdb.plataforma_configurar_proforma(1,true) as config'))[0].config;
check(Number(settings.ultimo_numero)===5,'reactivar recupera el contador anterior');
const other=(await q('select * from myappdb.empresas_proforma where empresa_id=2'))[0];
const otherUpdated=(await q('select myappdb.ajustar_contador_proforma($1,$2,$3,2) as config',[200,other.ultimo_numero,other.actualizado_en]))[0].config;
check(Number(otherUpdated.ultimo_numero)===200,'dueño ajusta contador desde empresa elegida en plataforma');
await db.exec("reset role;");
check((await q('select * from myappdb.ncf_secuencias')).length===1,'habilitar y ajustar no crea rangos DGII E332');
console.log(`${passed} verificaciones SQL proforma correctas`);
await db.close();
