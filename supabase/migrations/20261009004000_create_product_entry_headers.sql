create table if not exists myappdb.product_entry_headers (
  id bigint generated by default as identity primary key,
  empresa_id integer not null default private.current_empresa_id() references myappdb.empresas(id) on delete restrict,
  codigo text not null,
  suplidor_id integer not null references myappdb.suplidores(id) on delete restrict,
  fecha date not null default current_date,
  referencia text,
  orden_compra text,
  fecha_factura_suplidor date,
  codigo_usuario text,
  nombre_usuario text,
  notas text,
  created_at timestamptz not null default now(),
  created_by uuid default auth.uid(),
  unique (empresa_id, codigo)
);

alter table myappdb.product_entries
  add column if not exists entrada_id bigint references myappdb.product_entry_headers(id) on delete cascade;

create index if not exists product_entry_headers_empresa_fecha_idx
  on myappdb.product_entry_headers (empresa_id, fecha desc);

create index if not exists product_entries_entrada_id_idx
  on myappdb.product_entries (entrada_id);

alter table myappdb.product_entry_headers enable row level security;
grant select, insert, update, delete on myappdb.product_entry_headers to authenticated;
grant usage, select on sequence myappdb.product_entry_headers_id_seq to authenticated;

drop policy if exists product_entry_headers_tenant_access on myappdb.product_entry_headers;
create policy product_entry_headers_tenant_access
on myappdb.product_entry_headers for all to authenticated
using (empresa_id = private.current_empresa_id())
with check (empresa_id = private.current_empresa_id());

-- Preserve historic lines by converting each existing line into an entry header.
insert into myappdb.product_entry_headers (empresa_id, codigo, suplidor_id, fecha, referencia, notas)
select pe.empresa_id, 'LEGACY-' || pe.id::text, pe.suplidor_id, pe.fecha, pe.referencia, pe.notas
from myappdb.product_entries pe
where pe.entrada_id is null
  and pe.suplidor_id is not null;

update myappdb.product_entries pe
set entrada_id = h.id
from myappdb.product_entry_headers h
where pe.entrada_id is null
  and h.empresa_id = pe.empresa_id
  and h.codigo = 'LEGACY-' || pe.id::text;

create or replace function myappdb.guardar_lineas_entrada(
  p_entrada_id bigint,
  p_empresa_id integer,
  p_lineas jsonb
)
returns void
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_linea jsonb;
  v_producto_id integer;
  v_cantidad numeric;
  v_costo numeric;
begin
  if jsonb_typeof(p_lineas) <> 'array' or jsonb_array_length(p_lineas) = 0 then
    raise exception 'Debe indicar al menos un producto para la entrada';
  end if;

  for v_linea in select value from jsonb_array_elements(p_lineas)
  loop
    v_producto_id := nullif(v_linea ->> 'producto_id', '')::integer;
    v_cantidad := nullif(v_linea ->> 'cantidad', '')::numeric;
    v_costo := nullif(v_linea ->> 'costo_unitario', '')::numeric;

    if v_producto_id is null or v_cantidad is null or v_cantidad <= 0 or v_costo is null or v_costo < 0 then
      raise exception 'Las líneas de la entrada no son válidas';
    end if;

    perform 1 from myappdb.products
    where id = v_producto_id and empresa_id = p_empresa_id
    for update;
    if not found then
      raise exception 'El producto % no pertenece a la empresa activa', v_producto_id;
    end if;

    insert into myappdb.product_entries (empresa_id, entrada_id, producto_id, suplidor_id, fecha, cantidad, costo_unitario, referencia, notas)
    select p_empresa_id, p_entrada_id, v_producto_id, h.suplidor_id, h.fecha, v_cantidad, v_costo, h.referencia, h.notas
    from myappdb.product_entry_headers h
    where h.id = p_entrada_id;

    update myappdb.products
    set existencia = coalesce(existencia, 0) + v_cantidad,
        costo = v_costo
    where id = v_producto_id and empresa_id = p_empresa_id;
  end loop;
end;
$$;

create or replace function myappdb.crear_entrada_productos(
  p_suplidor_id integer,
  p_fecha date,
  p_referencia text,
  p_orden_compra text,
  p_fecha_factura_suplidor date,
  p_codigo_usuario text,
  p_nombre_usuario text,
  p_notas text,
  p_lineas jsonb
)
returns bigint
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_empresa_id integer := private.current_empresa_id();
  v_entrada_id bigint;
begin
  perform 1 from myappdb.suplidores where id = p_suplidor_id and empresa_id = v_empresa_id;
  if not found then raise exception 'El suplidor no existe o no pertenece a la empresa activa'; end if;

  insert into myappdb.product_entry_headers (empresa_id, codigo, suplidor_id, fecha, referencia, orden_compra, fecha_factura_suplidor, codigo_usuario, nombre_usuario, notas)
  values (v_empresa_id, 'PENDIENTE', p_suplidor_id, coalesce(p_fecha, current_date), nullif(trim(p_referencia), ''), nullif(trim(p_orden_compra), ''), p_fecha_factura_suplidor, nullif(trim(p_codigo_usuario), ''), nullif(trim(p_nombre_usuario), ''), nullif(trim(p_notas), ''))
  returning id into v_entrada_id;

  update myappdb.product_entry_headers
  set codigo = 'ENT-' || lpad(v_entrada_id::text, 6, '0')
  where id = v_entrada_id;

  perform myappdb.guardar_lineas_entrada(v_entrada_id, v_empresa_id, p_lineas);
  return v_entrada_id;
end;
$$;

create or replace function myappdb.actualizar_entrada_productos(
  p_entrada_id bigint,
  p_suplidor_id integer,
  p_fecha date,
  p_referencia text,
  p_orden_compra text,
  p_fecha_factura_suplidor date,
  p_codigo_usuario text,
  p_nombre_usuario text,
  p_notas text,
  p_lineas jsonb
)
returns void
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_empresa_id integer := private.current_empresa_id();
  v_linea record;
begin
  perform 1 from myappdb.product_entry_headers
  where id = p_entrada_id and empresa_id = v_empresa_id for update;
  if not found then raise exception 'La entrada no existe o no pertenece a la empresa activa'; end if;

  perform 1 from myappdb.suplidores where id = p_suplidor_id and empresa_id = v_empresa_id;
  if not found then raise exception 'El suplidor no existe o no pertenece a la empresa activa'; end if;

  for v_linea in select producto_id, cantidad from myappdb.product_entries where entrada_id = p_entrada_id
  loop
    update myappdb.products
    set existencia = greatest(0, coalesce(existencia, 0) - v_linea.cantidad)
    where id = v_linea.producto_id and empresa_id = v_empresa_id;
  end loop;
  delete from myappdb.product_entries where entrada_id = p_entrada_id;

  update myappdb.product_entry_headers
  set suplidor_id = p_suplidor_id, fecha = coalesce(p_fecha, current_date), referencia = nullif(trim(p_referencia), ''),
      orden_compra = nullif(trim(p_orden_compra), ''), fecha_factura_suplidor = p_fecha_factura_suplidor,
      codigo_usuario = nullif(trim(p_codigo_usuario), ''), nombre_usuario = nullif(trim(p_nombre_usuario), ''), notas = nullif(trim(p_notas), '')
  where id = p_entrada_id;

  perform myappdb.guardar_lineas_entrada(p_entrada_id, v_empresa_id, p_lineas);
end;
$$;

create or replace function myappdb.eliminar_entrada_productos(p_entrada_id bigint)
returns void
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_empresa_id integer := private.current_empresa_id();
  v_linea record;
begin
  perform 1 from myappdb.product_entry_headers where id = p_entrada_id and empresa_id = v_empresa_id for update;
  if not found then raise exception 'La entrada no existe o no pertenece a la empresa activa'; end if;
  for v_linea in select producto_id, cantidad from myappdb.product_entries where entrada_id = p_entrada_id
  loop
    update myappdb.products set existencia = greatest(0, coalesce(existencia, 0) - v_linea.cantidad)
    where id = v_linea.producto_id and empresa_id = v_empresa_id;
  end loop;
  delete from myappdb.product_entry_headers where id = p_entrada_id;
end;
$$;

