begin;
-- ===========================================================================
-- Cuentas por cobrar
--   * Factura a crédito = forma_pago_codigo 4 o condicion_pago 'Credito', no anulada.
--   * Saldo = total - abonos de recibos activos - notas de crédito no rechazadas.
--   * Vence = fecha_factura + clients.dias_credito (30 por defecto).
--   * Los recibos solo se crean/anulan por RPC (validan saldo y empresa).
--   * clients.balance se mantiene al día con disparadores.
-- ===========================================================================

alter table myappdb.clients add column if not exists dias_credito integer not null default 30;
alter table myappdb.clients drop constraint if exists clients_dias_credito_check;
alter table myappdb.clients add constraint clients_dias_credito_check check (dias_credito between 0 and 365);
create table if not exists myappdb.recibos_cobro (
  id bigint generated by default as identity primary key,
  empresa_id integer not null references myappdb.empresas(id) on delete restrict,
  sucursal_id smallint not null,
  numero_recibo text not null,
  cliente_id integer references myappdb.clients(id) on delete restrict,
  cliente_nombre text not null,
  fecha date not null default current_date,
  forma_pago_codigo integer not null references myappdb.formapago(codigo),
  referencia text,
  monto_total numeric(14,2) not null check (monto_total > 0),
  notas text,
  estado text not null default 'Activo' check (estado in ('Activo', 'Anulado')),
  usuario_id integer references myappdb.usuarios(codusuario) on delete set null,
  usuario_nombre text,
  anulado_en timestamptz,
  anulado_por text,
  creado_en timestamptz not null default now(),
  unique (empresa_id, numero_recibo)
);
create table if not exists myappdb.recibo_cobro_aplicaciones (
  id bigint generated by default as identity primary key,
  recibo_id bigint not null references myappdb.recibos_cobro(id) on delete cascade,
  factura_id bigint not null references myappdb.facturas(id) on delete restrict,
  monto numeric(14,2) not null check (monto > 0),
  unique (recibo_id, factura_id)
);
create index if not exists recibos_cobro_empresa_fecha_idx on myappdb.recibos_cobro (empresa_id, fecha desc);
create index if not exists recibos_cobro_cliente_idx on myappdb.recibos_cobro (cliente_id);
create index if not exists recibos_cobro_usuario_idx on myappdb.recibos_cobro (usuario_id);
create index if not exists recibos_cobro_forma_pago_idx on myappdb.recibos_cobro (forma_pago_codigo);
create index if not exists recibo_cobro_aplicaciones_factura_idx on myappdb.recibo_cobro_aplicaciones (factura_id);
create index if not exists facturas_cliente_credito_idx on myappdb.facturas (cliente_id) where forma_pago_codigo = 4 or condicion_pago = 'Credito';
alter table myappdb.recibos_cobro enable row level security;
alter table myappdb.recibo_cobro_aplicaciones enable row level security;
drop policy if exists recibos_cobro_tenant_select on myappdb.recibos_cobro;
create policy recibos_cobro_tenant_select on myappdb.recibos_cobro for select to authenticated
  using (empresa_id = (select private.current_empresa_id()));
drop policy if exists recibo_cobro_aplicaciones_tenant_select on myappdb.recibo_cobro_aplicaciones;
create policy recibo_cobro_aplicaciones_tenant_select on myappdb.recibo_cobro_aplicaciones for select to authenticated
  using (exists (select 1 from myappdb.recibos_cobro r where r.id = recibo_id and r.empresa_id = (select private.current_empresa_id())));
-- Solo lectura directa; las escrituras van por las funciones de abajo.
revoke all on myappdb.recibos_cobro, myappdb.recibo_cobro_aplicaciones from anon, authenticated;
grant select on myappdb.recibos_cobro, myappdb.recibo_cobro_aplicaciones to authenticated;
grant all on myappdb.recibos_cobro, myappdb.recibo_cobro_aplicaciones to service_role;
-- ---------------------------------------------------------------------------
-- Vista de facturas a crédito con su saldo (respeta la seguridad del usuario)
-- ---------------------------------------------------------------------------
-- La instalación puede contener una versión anterior con columnas adicionales.
-- Reemplazarla dentro de esta transacción conserva los datos y deja el contrato
-- de la vista alineado con esta migración.
drop view if exists myappdb.cxc_facturas;
create or replace view myappdb.cxc_facturas
with (security_invoker = true) as
select
  f.id,
  f.idempres as empresa_id,
  f.idsucursal as sucursal_id,
  f.numero_factura,
  f.ncf,
  f.cliente_id,
  coalesce(c.nombre_completo, f.cliente_nombre) as cliente_nombre,
  coalesce(c.numero_documento, f.cliente_rnc) as cliente_documento,
  f.fecha_factura,
  (f.fecha_factura + coalesce(c.dias_credito, 30))::date as fecha_vencimiento,
  f.total,
  coalesce(ab.abonado, 0)::numeric(14,2) as abonado,
  coalesce(nc.notas_credito, 0)::numeric(14,2) as notas_credito,
  greatest(f.total - coalesce(ab.abonado, 0) - coalesce(nc.notas_credito, 0), 0)::numeric(14,2) as saldo,
  greatest(current_date - (f.fecha_factura + coalesce(c.dias_credito, 30)), 0) as dias_vencida
from myappdb.facturas f
left join myappdb.clients c on c.id = f.cliente_id
left join lateral (
  select sum(a.monto) as abonado
  from myappdb.recibo_cobro_aplicaciones a
  join myappdb.recibos_cobro r on r.id = a.recibo_id and r.estado = 'Activo'
  where a.factura_id = f.id
) ab on true
left join lateral (
  select sum(n.total) as notas_credito
  from myappdb.notas_credito n
  where n.factura_afectada_id = f.id and coalesce(n.estado_dgii, '') not ilike 'rechaz%'
) nc on true
where f.estado <> 'Anulada'
  and (f.forma_pago_codigo = 4 or f.condicion_pago = 'Credito');
grant select on myappdb.cxc_facturas to authenticated;
-- ---------------------------------------------------------------------------
-- Balance del cliente
-- ---------------------------------------------------------------------------
create or replace function private.recalcular_balance_cliente(p_cliente_id integer)
returns void
language sql
security definer
set search_path = ''
as $$
  update myappdb.clients c
  set balance = coalesce((select sum(v.saldo) from myappdb.cxc_facturas v where v.cliente_id = p_cliente_id), 0)
  where c.id = p_cliente_id;
$$;
revoke all on function private.recalcular_balance_cliente(integer) from public, anon, authenticated;
create or replace function private.tg_facturas_balance_cliente()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_op in ('UPDATE', 'DELETE') and old.cliente_id is not null then
    perform private.recalcular_balance_cliente(old.cliente_id);
  end if;
  if tg_op in ('INSERT', 'UPDATE') and new.cliente_id is not null
     and (tg_op = 'INSERT' or new.cliente_id is distinct from old.cliente_id) then
    perform private.recalcular_balance_cliente(new.cliente_id);
  end if;
  return null;
end;
$$;
drop trigger if exists facturas_balance_cliente on myappdb.facturas;
create trigger facturas_balance_cliente
  after insert or delete or update of total, estado, forma_pago_codigo, condicion_pago, cliente_id
  on myappdb.facturas
  for each row execute function private.tg_facturas_balance_cliente();
create or replace function private.tg_notas_credito_balance_cliente()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_cliente integer;
begin
  for v_cliente in
    select f.cliente_id from myappdb.facturas f
    where f.id in (
      case when tg_op <> 'INSERT' then old.factura_afectada_id end,
      case when tg_op <> 'DELETE' then new.factura_afectada_id end)
      and f.cliente_id is not null
  loop
    perform private.recalcular_balance_cliente(v_cliente);
  end loop;
  return null;
end;
$$;
drop trigger if exists notas_credito_balance_cliente on myappdb.notas_credito;
create trigger notas_credito_balance_cliente
  after insert or delete or update of total, estado_dgii, factura_afectada_id
  on myappdb.notas_credito
  for each row execute function private.tg_notas_credito_balance_cliente();
-- Una factura con abonos activos no se puede anular sin anular antes el recibo.
create or replace function private.tg_facturas_bloquear_anulacion_con_abonos()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.estado = 'Anulada' and old.estado is distinct from 'Anulada' and exists (
    select 1 from myappdb.recibo_cobro_aplicaciones a
    join myappdb.recibos_cobro r on r.id = a.recibo_id and r.estado = 'Activo'
    where a.factura_id = new.id
  ) then
    raise exception 'La factura % tiene abonos registrados. Anule primero los recibos de cobro.', new.numero_factura
      using errcode = '22023';
  end if;
  return new;
end;
$$;
drop trigger if exists facturas_bloquear_anulacion_con_abonos on myappdb.facturas;
create trigger facturas_bloquear_anulacion_con_abonos
  before update of estado on myappdb.facturas
  for each row execute function private.tg_facturas_bloquear_anulacion_con_abonos();
-- ---------------------------------------------------------------------------
-- Registrar un recibo de cobro
--   p_recibo: {customerId, date, paymentCode, reference, notes}
--   p_aplicaciones: [{invoiceId, amount}, ...]
-- ---------------------------------------------------------------------------
create or replace function myappdb.crear_recibo_cobro(p_recibo jsonb, p_aplicaciones jsonb)
returns table(id bigint, numero_recibo text)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_empresa_id integer;
  v_sucursal_id smallint;
  v_usuario_id integer;
  v_usuario_nombre text;
  v_empresa_nombre text;
  v_cliente_id integer := nullif(p_recibo ->> 'customerId', '')::integer;
  v_cliente_nombre text;
  v_forma_pago integer := coalesce(nullif(p_recibo ->> 'paymentCode', '')::integer, 1);
  v_fecha date := coalesce(nullif(p_recibo ->> 'date', '')::date, current_date);
  v_total numeric(14,2) := 0;
  v_aplicacion jsonb;
  v_factura_id bigint;
  v_monto numeric(14,2);
  v_saldo numeric(14,2);
  v_factura_cliente integer;
  v_ano smallint := extract(year from current_date)::smallint;
  v_consecutivo integer;
  v_numero text;
  v_recibo_id bigint;
begin
  select u.empresa_id, u.sucursal_id, u.codusuario, u.nombre_completo
  into v_empresa_id, v_sucursal_id, v_usuario_id, v_usuario_nombre
  from myappdb.usuarios u
  where u.auth_usuario_id = (select auth.uid()) and u.estado = 'Activo';
  if not found then
    raise exception 'No se encontró un usuario activo.' using errcode = '42501';
  end if;

  if v_cliente_id is null then
    raise exception 'Seleccione el cliente del recibo.' using errcode = '22023';
  end if;
  select c.nombre_completo into v_cliente_nombre
  from myappdb.clients c where c.id = v_cliente_id and c.empresa_id = v_empresa_id;
  if not found then
    raise exception 'El cliente no pertenece a su empresa.' using errcode = '42501';
  end if;

  if v_forma_pago = 4 then
    raise exception 'Un cobro no puede registrarse con la forma de pago "Venta a crédito".' using errcode = '22023';
  end if;
  if not exists (select 1 from myappdb.formapago fp where fp.codigo = v_forma_pago) then
    raise exception 'Forma de pago no válida.' using errcode = '22023';
  end if;

  if jsonb_array_length(coalesce(p_aplicaciones, '[]'::jsonb)) = 0 then
    raise exception 'Indique al menos una factura a la que aplicar el cobro.' using errcode = '22023';
  end if;

  -- Valida cada abono contra el saldo actual (bloqueando la factura).
  for v_aplicacion in select value from jsonb_array_elements(p_aplicaciones)
  loop
    v_factura_id := nullif(v_aplicacion ->> 'invoiceId', '')::bigint;
    v_monto := round(coalesce((v_aplicacion ->> 'amount')::numeric, 0), 2);
    if v_factura_id is null or v_monto <= 0 then
      raise exception 'Cada abono debe indicar la factura y un monto mayor que cero.' using errcode = '22023';
    end if;

    perform 1 from myappdb.facturas f where f.id = v_factura_id and f.idempres = v_empresa_id for update;
    if not found then
      raise exception 'Una de las facturas no pertenece a su empresa.' using errcode = '42501';
    end if;

    select v.saldo, v.cliente_id into v_saldo, v_factura_cliente
    from myappdb.cxc_facturas v where v.id = v_factura_id;
    if not found then
      raise exception 'La factura indicada no es una venta a crédito pendiente.' using errcode = '22023';
    end if;
    if v_factura_cliente is distinct from v_cliente_id then
      raise exception 'Todas las facturas del recibo deben ser del mismo cliente.' using errcode = '22023';
    end if;
    if v_monto > v_saldo then
      raise exception 'El abono de % supera el saldo pendiente de la factura (%).', v_monto, v_saldo using errcode = '22023';
    end if;
    v_total := v_total + v_monto;
  end loop;

  -- Número de recibo: RC + año + sucursal + consecutivo (contador_doc.recibo).
  select e.nombre_comercial into v_empresa_nombre from myappdb.empresas e where e.id = v_empresa_id;
  insert into myappdb.contador_doc (id_empres, nom_empresa, ano, sucursal_id, factura, recibo)
  values (v_empresa_id, v_empresa_nombre, v_ano, v_sucursal_id, 0, 1)
  on conflict (id_empres, ano, sucursal_id)
  do update set recibo = coalesce(myappdb.contador_doc.recibo, 0) + 1
  returning recibo into v_consecutivo;
  v_numero := 'RC' || lpad(v_ano::text, 4, '0') || lpad(v_sucursal_id::text, 2, '0') || lpad(v_consecutivo::text, 5, '0');

  insert into myappdb.recibos_cobro (
    empresa_id, sucursal_id, numero_recibo, cliente_id, cliente_nombre, fecha, forma_pago_codigo,
    referencia, monto_total, notas, usuario_id, usuario_nombre
  ) values (
    v_empresa_id, v_sucursal_id, v_numero, v_cliente_id, v_cliente_nombre, v_fecha, v_forma_pago,
    nullif(trim(p_recibo ->> 'reference'), ''), v_total, nullif(trim(p_recibo ->> 'notes'), ''),
    v_usuario_id, v_usuario_nombre
  ) returning recibos_cobro.id into v_recibo_id;

  insert into myappdb.recibo_cobro_aplicaciones (recibo_id, factura_id, monto)
  select v_recibo_id, (a.value ->> 'invoiceId')::bigint, round((a.value ->> 'amount')::numeric, 2)
  from jsonb_array_elements(p_aplicaciones) a;

  perform private.recalcular_balance_cliente(v_cliente_id);

  return query select v_recibo_id, v_numero;
end;
$$;
revoke all on function myappdb.crear_recibo_cobro(jsonb, jsonb) from public, anon;
grant execute on function myappdb.crear_recibo_cobro(jsonb, jsonb) to authenticated, service_role;
-- ---------------------------------------------------------------------------
-- Anular un recibo (solo administrador)
-- ---------------------------------------------------------------------------
create or replace function myappdb.anular_recibo_cobro(p_recibo_id bigint, p_motivo text default null)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_empresa_id integer := private.current_empresa_id();
  v_cliente_id integer;
  v_estado text;
  v_usuario text;
begin
  if not private.current_user_is_admin() then
    raise exception 'Solo un administrador puede anular recibos de cobro.' using errcode = '42501';
  end if;

  select r.cliente_id, r.estado into v_cliente_id, v_estado
  from myappdb.recibos_cobro r
  where r.id = p_recibo_id and r.empresa_id = v_empresa_id
  for update;
  if not found then
    raise exception 'No se encontró el recibo en su empresa.' using errcode = '42501';
  end if;
  if v_estado = 'Anulado' then
    raise exception 'El recibo ya está anulado.' using errcode = '22023';
  end if;

  select u.nombre_completo into v_usuario from myappdb.usuarios u where u.auth_usuario_id = (select auth.uid());

  update myappdb.recibos_cobro
  set estado = 'Anulado', anulado_en = now(), anulado_por = v_usuario,
      notas = case when nullif(trim(p_motivo), '') is null then notas
                   else concat_ws(' | ', notas, 'Anulado: ' || trim(p_motivo)) end
  where recibos_cobro.id = p_recibo_id;

  if v_cliente_id is not null then
    perform private.recalcular_balance_cliente(v_cliente_id);
  end if;
end;
$$;
revoke all on function myappdb.anular_recibo_cobro(bigint, text) from public, anon;
grant execute on function myappdb.anular_recibo_cobro(bigint, text) to authenticated, service_role;
-- Sincroniza el balance actual de todos los clientes.
do $$
declare v_id integer;
begin
  for v_id in select c.id from myappdb.clients c loop
    perform private.recalcular_balance_cliente(v_id);
  end loop;
end;
$$;
commit;
