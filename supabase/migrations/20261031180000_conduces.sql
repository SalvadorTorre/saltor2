begin;

-- ===========================================================================
-- Conduce de despacho
--  * Se crea desde una orden de venta o una factura (no anuladas).
--  * Permite despachos parciales: cada línea despacha como máximo lo que
--    queda pendiente (cantidad del documento menos lo despachado en conduces
--    no anulados).
--  * No mueve inventario: el inventario ya lo rebaja la factura.
--  * Estados: Despachado → Entregado; o Anulado (libera lo despachado).
-- ===========================================================================

alter table myappdb.contador_doc add column if not exists conduce integer not null default 0;

create table if not exists myappdb.conduces (
  id bigint generated by default as identity primary key,
  empresa_id integer not null default private.current_empresa_id() references myappdb.empresas(id) on delete restrict,
  sucursal_id smallint,
  numero text not null,
  fecha date not null default ((now() at time zone 'America/Santo_Domingo')::date),
  origen_tipo text not null check (origen_tipo in ('Orden de venta', 'Factura')),
  orden_id bigint references myappdb.ordenventa(id) on delete restrict,
  factura_id bigint references myappdb.facturas(id) on delete restrict,
  numero_origen text not null,
  cliente_id integer,
  cliente_nombre text not null,
  cliente_rnc text,
  cliente_telefono text,
  direccion_entrega text,
  chofer text,
  vehiculo text,
  notas text,
  estado text not null default 'Despachado' check (estado in ('Despachado', 'Entregado', 'Anulado')),
  usuario_id integer,
  usuario_nombre text,
  entregado_en timestamptz,
  recibido_por text,
  anulado_en timestamptz,
  anulado_por text,
  motivo_anulacion text,
  impreso_en timestamptz,
  creado_en timestamptz not null default now(),
  constraint conduces_numero_key unique (empresa_id, numero),
  constraint conduces_origen_check check (
    (origen_tipo = 'Orden de venta' and orden_id is not null and factura_id is null)
    or (origen_tipo = 'Factura' and factura_id is not null and orden_id is null))
);
create index if not exists conduces_orden_idx on myappdb.conduces (orden_id);
create index if not exists conduces_factura_idx on myappdb.conduces (factura_id);
create index if not exists conduces_empresa_fecha_idx on myappdb.conduces (empresa_id, fecha desc);

create table if not exists myappdb.conduce_detalles (
  id bigint generated by default as identity primary key,
  conduce_id bigint not null references myappdb.conduces(id) on delete cascade,
  linea_origen_id bigint not null,
  producto_id integer,
  codigo_producto text,
  descripcion text not null,
  unidad text,
  cantidad_documento numeric(14,2) not null,
  cantidad numeric(14,2) not null check (cantidad > 0)
);
create index if not exists conduce_detalles_conduce_idx on myappdb.conduce_detalles (conduce_id);
create index if not exists conduce_detalles_linea_idx on myappdb.conduce_detalles (linea_origen_id);

alter table myappdb.conduces enable row level security;
alter table myappdb.conduce_detalles enable row level security;

drop policy if exists conduces_tenant_select on myappdb.conduces;
create policy conduces_tenant_select on myappdb.conduces for select to authenticated
  using (empresa_id = (select private.current_empresa_id()));

drop policy if exists conduces_tenant_update on myappdb.conduces;
create policy conduces_tenant_update on myappdb.conduces for update to authenticated
  using (empresa_id = (select private.current_empresa_id()))
  with check (empresa_id = (select private.current_empresa_id()));

drop policy if exists conduce_detalles_tenant_select on myappdb.conduce_detalles;
create policy conduce_detalles_tenant_select on myappdb.conduce_detalles for select to authenticated
  using (exists (select 1 from myappdb.conduces c where c.id = conduce_detalles.conduce_id
                 and c.empresa_id = (select private.current_empresa_id())));

revoke all on myappdb.conduces, myappdb.conduce_detalles from public, anon, authenticated;
grant select on myappdb.conduces, myappdb.conduce_detalles to authenticated;
grant update (impreso_en) on myappdb.conduces to authenticated;
grant all on myappdb.conduces, myappdb.conduce_detalles to service_role;

-- Número: año + sucursal + consecutivo, igual que las órdenes de venta.
create or replace function private.siguiente_numero_conduce(p_empresa_id integer, p_sucursal_id smallint)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_ano smallint := extract(year from current_date)::smallint;
  v_consecutivo integer;
begin
  insert into myappdb.contador_doc (id_empres, nom_empresa, ano, sucursal_id, factura, cotizacion, nota_credito, gasto_menores, recibo, ordenventa, conduce)
  values (p_empresa_id, (select e.nombre_comercial from myappdb.empresas e where e.id = p_empresa_id), v_ano, p_sucursal_id, 0, 0, 0, 0, 0, 0, 1)
  on conflict (id_empres, ano, sucursal_id) do update
    set conduce = coalesce(myappdb.contador_doc.conduce, 0) + 1
  returning conduce into v_consecutivo;
  return lpad(v_ano::text, 4, '0') || lpad(p_sucursal_id::text, 2, '0') || lpad(v_consecutivo::text, 5, '0');
end;
$$;
revoke all on function private.siguiente_numero_conduce(integer, smallint) from public, anon, authenticated;

-- Documento (orden o factura) con lo pendiente por despachar en cada línea.
create or replace function myappdb.conduce_documento(p_origen text, p_id bigint default null, p_numero text default null)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_empresa integer := private.current_empresa_id();
  v_doc jsonb;
  v_id bigint;
  v_lineas jsonb;
begin
  if v_empresa is null then raise exception 'No hay empresa activa.' using errcode = '42501'; end if;

  if p_origen = 'Factura' then
    select jsonb_build_object('origen', 'Factura', 'id', f.id, 'numero', f.numero_factura, 'fecha', f.fecha_factura, 'ncf', f.ncf,
             'clienteId', f.cliente_id, 'cliente', f.cliente_nombre, 'rnc', f.cliente_rnc, 'telefono', f.cliente_telefono,
             'direccion', coalesce(f.cliente_direccion, c.direccion), 'estado', f.estado), f.id
      into v_doc, v_id
      from myappdb.facturas f left join myappdb.clients c on c.id = f.cliente_id
     where f.idempres = v_empresa and (f.id = p_id or (p_id is null and f.numero_factura = trim(p_numero)))
     limit 1;
    if v_id is null then raise exception 'No se encontró la factura.' using errcode = 'P0002'; end if;
    if v_doc ->> 'estado' = 'Anulada' then raise exception 'La factura está anulada.' using errcode = '22023'; end if;
    select coalesce(jsonb_agg(jsonb_build_object(
             'lineaId', d.id, 'productoId', d.producto_id, 'codigo', coalesce(d.codigo_producto, p.codigo), 'descripcion', d.descripcion,
             'unidad', coalesce(p.unidad, 'UNIDAD'), 'cantidad', d.cantidad, 'despachado', coalesce(x.despachado, 0),
             'pendiente', greatest(d.cantidad - coalesce(x.despachado, 0), 0)) order by d.id), '[]'::jsonb)
      into v_lineas
      from myappdb.factura_detalles d
      left join myappdb.products p on p.id = d.producto_id
      left join lateral (select sum(cd.cantidad) despachado from myappdb.conduce_detalles cd
                           join myappdb.conduces co on co.id = cd.conduce_id and co.estado <> 'Anulado' and co.factura_id = v_id
                          where cd.linea_origen_id = d.id) x on true
     where d.factura_id = v_id;
  elsif p_origen = 'Orden de venta' then
    select jsonb_build_object('origen', 'Orden de venta', 'id', o.id, 'numero', o.numero_orden, 'fecha', o.fecha_orden, 'ncf', null,
             'clienteId', o.cliente_id, 'cliente', o.cliente_nombre, 'rnc', o.cliente_rnc, 'telefono', o.cliente_telefono,
             'direccion', coalesce(o.cliente_direccion, c.direccion), 'estado', o.estado), o.id
      into v_doc, v_id
      from myappdb.ordenventa o left join myappdb.clients c on c.id = o.cliente_id
     where o.idempres = v_empresa and (o.id = p_id or (p_id is null and o.numero_orden = trim(p_numero)))
     limit 1;
    if v_id is null then raise exception 'No se encontró la orden de venta.' using errcode = 'P0002'; end if;
    if v_doc ->> 'estado' = 'Anulada' then raise exception 'La orden de venta está anulada.' using errcode = '22023'; end if;
    select coalesce(jsonb_agg(jsonb_build_object(
             'lineaId', d.id, 'productoId', d.producto_id, 'codigo', coalesce(d.codigo_producto, p.codigo), 'descripcion', d.descripcion,
             'unidad', coalesce(p.unidad, 'UNIDAD'), 'cantidad', d.cantidad, 'despachado', coalesce(x.despachado, 0),
             'pendiente', greatest(d.cantidad - coalesce(x.despachado, 0), 0)) order by d.id), '[]'::jsonb)
      into v_lineas
      from myappdb.ordenventa_detalle d
      left join myappdb.products p on p.id = d.producto_id
      left join lateral (select sum(cd.cantidad) despachado from myappdb.conduce_detalles cd
                           join myappdb.conduces co on co.id = cd.conduce_id and co.estado <> 'Anulado' and co.orden_id = v_id
                          where cd.linea_origen_id = d.id) x on true
     where d.ordenventa_id = v_id;
  else
    raise exception 'Origen no válido: %', p_origen using errcode = '22023';
  end if;

  return v_doc || jsonb_build_object('lineas', v_lineas);
end;
$$;
revoke all on function myappdb.conduce_documento(text, bigint, text) from public, anon;
grant execute on function myappdb.conduce_documento(text, bigint, text) to authenticated;

-- Crear el conduce (valida cada cantidad contra lo pendiente).
create or replace function myappdb.crear_conduce(p_conduce jsonb, p_detalles jsonb)
returns table (id bigint, numero text)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_empresa integer; v_sucursal smallint; v_usuario integer; v_usuario_nombre text;
  v_origen text := p_conduce ->> 'origen';
  v_doc_id bigint := nullif(p_conduce ->> 'documentoId', '')::bigint;
  v_doc jsonb; v_linea jsonb; v_det jsonb; v_cantidad numeric; v_total numeric := 0;
  v_id bigint; v_numero text;
begin
  select u.empresa_id, u.sucursal_id, u.codusuario, u.nombre_completo into v_empresa, v_sucursal, v_usuario, v_usuario_nombre
    from myappdb.usuarios u where u.auth_usuario_id = (select auth.uid()) and u.estado = 'Activo';
  if not found then raise exception 'No se encontró un usuario activo.' using errcode = '42501'; end if;
  if v_doc_id is null then raise exception 'Indique la orden de venta o la factura.' using errcode = '22023'; end if;

  -- Bloquea el documento para que dos conduces simultáneos no despachen de más.
  if v_origen = 'Factura' then
    perform 1 from myappdb.facturas f where f.id = v_doc_id and f.idempres = v_empresa for update;
  elsif v_origen = 'Orden de venta' then
    perform 1 from myappdb.ordenventa o where o.id = v_doc_id and o.idempres = v_empresa for update;
  end if;

  v_doc := myappdb.conduce_documento(v_origen, v_doc_id, null);

  if jsonb_array_length(coalesce(p_detalles, '[]'::jsonb)) = 0 then
    raise exception 'Indique al menos un producto a despachar.' using errcode = '22023';
  end if;
  for v_det in select value from jsonb_array_elements(p_detalles) loop
    v_cantidad := round(coalesce((v_det ->> 'cantidad')::numeric, 0), 2);
    continue when v_cantidad <= 0;
    select l.value into v_linea from jsonb_array_elements(v_doc -> 'lineas') l where (l.value ->> 'lineaId')::bigint = (v_det ->> 'lineaId')::bigint;
    if v_linea is null then raise exception 'Una de las líneas no pertenece al documento.' using errcode = '22023'; end if;
    if v_cantidad > (v_linea ->> 'pendiente')::numeric then
      raise exception 'La cantidad de "%" (%) supera lo pendiente por despachar (%).', v_linea ->> 'descripcion', v_cantidad, v_linea ->> 'pendiente' using errcode = '22023';
    end if;
    v_total := v_total + v_cantidad;
  end loop;
  if v_total <= 0 then raise exception 'Indique al menos un producto a despachar.' using errcode = '22023'; end if;

  v_numero := private.siguiente_numero_conduce(v_empresa, v_sucursal);

  insert into myappdb.conduces (empresa_id, sucursal_id, numero, fecha, origen_tipo, orden_id, factura_id, numero_origen,
                                cliente_id, cliente_nombre, cliente_rnc, cliente_telefono, direccion_entrega, chofer, vehiculo, notas,
                                usuario_id, usuario_nombre)
  values (v_empresa, v_sucursal, v_numero,
          coalesce(nullif(p_conduce ->> 'fecha', '')::date, (now() at time zone 'America/Santo_Domingo')::date),
          v_origen,
          case when v_origen = 'Orden de venta' then v_doc_id end,
          case when v_origen = 'Factura' then v_doc_id end,
          v_doc ->> 'numero', nullif(v_doc ->> 'clienteId', '')::integer, coalesce(v_doc ->> 'cliente', 'CLIENTE'), v_doc ->> 'rnc', v_doc ->> 'telefono',
          coalesce(nullif(trim(p_conduce ->> 'direccion'), ''), v_doc ->> 'direccion'),
          nullif(trim(p_conduce ->> 'chofer'), ''), nullif(trim(p_conduce ->> 'vehiculo'), ''), nullif(trim(p_conduce ->> 'notas'), ''),
          v_usuario, v_usuario_nombre)
  returning conduces.id into v_id;

  insert into myappdb.conduce_detalles (conduce_id, linea_origen_id, producto_id, codigo_producto, descripcion, unidad, cantidad_documento, cantidad)
  select v_id, (l.value ->> 'lineaId')::bigint, nullif(l.value ->> 'productoId', '')::integer, l.value ->> 'codigo', l.value ->> 'descripcion',
         l.value ->> 'unidad', (l.value ->> 'cantidad')::numeric, round((d.value ->> 'cantidad')::numeric, 2)
    from jsonb_array_elements(p_detalles) d
    join jsonb_array_elements(v_doc -> 'lineas') l on (l.value ->> 'lineaId')::bigint = (d.value ->> 'lineaId')::bigint
   where round(coalesce((d.value ->> 'cantidad')::numeric, 0), 2) > 0;

  return query select v_id, v_numero;
end;
$$;
revoke all on function myappdb.crear_conduce(jsonb, jsonb) from public, anon;
grant execute on function myappdb.crear_conduce(jsonb, jsonb) to authenticated;

create or replace function myappdb.marcar_conduce_entregado(p_id bigint, p_recibido_por text default null)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare v_estado text;
begin
  select estado into v_estado from myappdb.conduces where id = p_id and empresa_id = private.current_empresa_id() for update;
  if v_estado is null then raise exception 'Conduce no encontrado.' using errcode = '42501'; end if;
  if v_estado <> 'Despachado' then raise exception 'El conduce está %.', lower(v_estado) using errcode = '22023'; end if;
  update myappdb.conduces set estado = 'Entregado', entregado_en = now(), recibido_por = nullif(trim(p_recibido_por), '') where id = p_id;
end;
$$;
revoke all on function myappdb.marcar_conduce_entregado(bigint, text) from public, anon;
grant execute on function myappdb.marcar_conduce_entregado(bigint, text) to authenticated;

create or replace function myappdb.anular_conduce(p_id bigint, p_motivo text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare v_estado text; v_usuario text;
begin
  select nombre_completo into v_usuario from myappdb.usuarios where auth_usuario_id = (select auth.uid()) and estado = 'Activo';
  select estado into v_estado from myappdb.conduces where id = p_id and empresa_id = private.current_empresa_id() for update;
  if v_estado is null then raise exception 'Conduce no encontrado.' using errcode = '42501'; end if;
  if v_estado = 'Anulado' then raise exception 'El conduce ya está anulado.' using errcode = '22023'; end if;
  if nullif(trim(p_motivo), '') is null then raise exception 'Indique el motivo de la anulación.' using errcode = '22023'; end if;
  update myappdb.conduces set estado = 'Anulado', anulado_en = now(), anulado_por = v_usuario, motivo_anulacion = trim(p_motivo) where id = p_id;
end;
$$;
revoke all on function myappdb.anular_conduce(bigint, text) from public, anon;
grant execute on function myappdb.anular_conduce(bigint, text) to authenticated;

