create table if not exists myappdb.product_entries (
  id bigint generated by default as identity primary key,
  empresa_id integer not null default private.current_empresa_id() references myappdb.empresas(id) on delete restrict,
  producto_id integer not null references myappdb.products(id) on delete restrict,
  suplidor_id integer references myappdb.suplidores(id) on delete set null,
  fecha date not null default current_date,
  cantidad numeric(14, 2) not null check (cantidad > 0),
  costo_unitario numeric(14, 2) not null check (costo_unitario >= 0),
  referencia text,
  notas text,
  created_at timestamptz not null default now(),
  created_by uuid default auth.uid()
);

create index if not exists product_entries_empresa_fecha_idx on myappdb.product_entries (empresa_id, fecha desc);
create index if not exists product_entries_empresa_producto_idx on myappdb.product_entries (empresa_id, producto_id);

alter table myappdb.product_entries enable row level security;
grant select, insert, update, delete on myappdb.product_entries to authenticated;
grant usage, select on sequence myappdb.product_entries_id_seq to authenticated;

create policy product_entries_tenant_access
on myappdb.product_entries for all to authenticated
using (empresa_id = private.current_empresa_id())
with check (empresa_id = private.current_empresa_id());

create or replace function myappdb.registrar_entrada_producto(
  p_producto_id integer,
  p_suplidor_id integer,
  p_fecha date,
  p_cantidad numeric,
  p_costo_unitario numeric,
  p_referencia text default null,
  p_notas text default null
)
returns bigint
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_empresa_id integer := private.current_empresa_id();
  v_entrada_id bigint;
begin
  if p_cantidad is null or p_cantidad <= 0 then
    raise exception 'La cantidad debe ser mayor que cero';
  end if;

  if p_costo_unitario is null or p_costo_unitario < 0 then
    raise exception 'El costo unitario no es válido';
  end if;

  perform 1 from myappdb.products
  where id = p_producto_id and empresa_id = v_empresa_id
  for update;

  if not found then
    raise exception 'El producto no existe o no pertenece a la empresa activa';
  end if;

  if p_suplidor_id is not null then
    perform 1 from myappdb.suplidores
    where id = p_suplidor_id and empresa_id = v_empresa_id;

    if not found then
      raise exception 'El suplidor no existe o no pertenece a la empresa activa';
    end if;
  end if;

  insert into myappdb.product_entries (
    empresa_id, producto_id, suplidor_id, fecha, cantidad, costo_unitario, referencia, notas
  ) values (
    v_empresa_id, p_producto_id, p_suplidor_id, coalesce(p_fecha, current_date), p_cantidad,
    p_costo_unitario, nullif(trim(p_referencia), ''), nullif(trim(p_notas), '')
  ) returning id into v_entrada_id;

  update myappdb.products
  set existencia = coalesce(existencia, 0) + p_cantidad,
      costo = p_costo_unitario
  where id = p_producto_id and empresa_id = v_empresa_id;

  return v_entrada_id;
end;
$$;

revoke execute on function myappdb.registrar_entrada_producto(integer, integer, date, numeric, numeric, text, text) from public;
grant execute on function myappdb.registrar_entrada_producto(integer, integer, date, numeric, numeric, text, text) to authenticated;

create or replace function myappdb.eliminar_entrada_producto(p_entrada_id bigint)
returns void
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_entrada myappdb.product_entries%rowtype;
begin
  select * into v_entrada from myappdb.product_entries
  where id = p_entrada_id and empresa_id = private.current_empresa_id()
  for update;

  if not found then
    raise exception 'La entrada no existe o no pertenece a la empresa activa';
  end if;

  update myappdb.products
  set existencia = greatest(0, coalesce(existencia, 0) - v_entrada.cantidad)
  where id = v_entrada.producto_id and empresa_id = v_entrada.empresa_id;

  delete from myappdb.product_entries where id = v_entrada.id;
end;
$$;

revoke execute on function myappdb.eliminar_entrada_producto(bigint) from public;
grant execute on function myappdb.eliminar_entrada_producto(bigint) to authenticated;
