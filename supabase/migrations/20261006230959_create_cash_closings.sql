begin;

create or replace function private.current_sucursal_id()
returns smallint
language sql
stable
security definer
set search_path = ''
as $$
  select u.sucursal_id
  from myappdb.usuarios u
  where u.auth_usuario_id = (select auth.uid())
    and u.estado = 'Activo'
  limit 1
$$;

revoke all on function private.current_sucursal_id() from public;
grant execute on function private.current_sucursal_id() to authenticated, service_role;

create table if not exists myappdb.cierres_caja (
  id bigint generated by default as identity primary key,
  empresa_id integer not null default private.current_empresa_id() references myappdb.empresas(id) on delete restrict,
  empresa_nombre text not null,
  empresa_rnc text,
  sucursal_id smallint not null,
  sucursal_nombre text not null,
  usuario_id integer not null references myappdb.usuarios(codusuario) on delete restrict,
  cajero_nombre text not null,
  factura_desde text not null,
  factura_hasta text not null,
  cantidad_facturas integer not null default 0 check (cantidad_facturas >= 0),
  total_efectivo numeric(14, 2) not null default 0,
  total_tarjetas numeric(14, 2) not null default 0,
  total_depositos numeric(14, 2) not null default 0,
  total_cheques numeric(14, 2) not null default 0,
  total_credito numeric(14, 2) not null default 0,
  total_pendiente numeric(14, 2) not null default 0,
  valores_cobrados numeric(14, 2) not null default 0,
  valores_no_cobrados numeric(14, 2) not null default 0,
  total_cierre numeric(14, 2) not null default 0,
  nota text,
  estado text not null default 'Confirmado' check (estado in ('Confirmado', 'Anulado')),
  cerrado_en timestamptz not null default now(),
  impreso_en timestamptz,
  creado_en timestamptz not null default now()
);

create table if not exists myappdb.cierre_caja_facturas (
  id bigint generated by default as identity primary key,
  cierre_caja_id bigint not null references myappdb.cierres_caja(id) on delete cascade,
  factura_id bigint not null references myappdb.facturas(id) on delete restrict,
  numero_factura text not null,
  fecha_factura date not null,
  cliente_nombre text not null,
  tipo_ncf text,
  forma_pago_codigo smallint,
  condicion_pago text not null,
  cobrada_en_cierre boolean not null default false,
  total numeric(14, 2) not null default 0,
  creado_en timestamptz not null default now(),
  unique (factura_id)
);

alter table myappdb.facturas add column if not exists cierre_caja_id bigint references myappdb.cierres_caja(id) on delete restrict;
alter table myappdb.facturas add column if not exists numero_cierre bigint;

create index if not exists cierres_caja_empresa_fecha_idx on myappdb.cierres_caja (empresa_id, cerrado_en desc);
create index if not exists cierres_caja_empresa_sucursal_idx on myappdb.cierres_caja (empresa_id, sucursal_id, cerrado_en desc);
create index if not exists cierre_caja_facturas_cierre_idx on myappdb.cierre_caja_facturas (cierre_caja_id);
create index if not exists facturas_cierre_caja_idx on myappdb.facturas (cierre_caja_id) where cierre_caja_id is not null;
create index if not exists facturas_numero_cierre_idx on myappdb.facturas (numero_cierre) where numero_cierre is not null;

create or replace function myappdb.bloquear_factura_cerrada()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if old.cierre_caja_id is not null then
    raise exception 'La factura % pertenece al cierre % y no puede modificarse.', old.numero_factura, old.numero_cierre
      using errcode = '55000';
  end if;
  return new;
end;
$$;

drop trigger if exists facturas_bloquear_cierre on myappdb.facturas;
create trigger facturas_bloquear_cierre
before update or delete on myappdb.facturas
for each row execute function myappdb.bloquear_factura_cerrada();

alter table myappdb.cierres_caja enable row level security;
alter table myappdb.cierre_caja_facturas enable row level security;

create policy cierres_caja_tenant_access on myappdb.cierres_caja for all to authenticated
  using (empresa_id = (select private.current_empresa_id()) and sucursal_id = (select private.current_sucursal_id()))
  with check (empresa_id = (select private.current_empresa_id()) and sucursal_id = (select private.current_sucursal_id()));

create policy cierre_caja_facturas_tenant_access on myappdb.cierre_caja_facturas for select to authenticated
  using (exists (
    select 1 from myappdb.cierres_caja c
    where c.id = cierre_caja_id and c.empresa_id = (select private.current_empresa_id())
  ));

drop policy if exists cierre_caja_facturas_insert_tenant on myappdb.cierre_caja_facturas;
create policy cierre_caja_facturas_insert_tenant on myappdb.cierre_caja_facturas for insert to authenticated
  with check (exists (
    select 1 from myappdb.cierres_caja c
    where c.id = cierre_caja_id
      and c.empresa_id = (select private.current_empresa_id())
      and c.sucursal_id = (select private.current_sucursal_id())
  ));

grant select, insert, update on myappdb.cierres_caja to authenticated;
grant select, insert on myappdb.cierre_caja_facturas to authenticated;
grant usage, select on sequence myappdb.cierres_caja_id_seq, myappdb.cierre_caja_facturas_id_seq to authenticated;

create or replace function myappdb.crear_cierre_caja(
  p_factura_desde text,
  p_factura_hasta text,
  p_nota text default null
)
returns table (
  id bigint,
  cantidad_facturas integer,
  total_efectivo numeric,
  total_tarjetas numeric,
  total_depositos numeric,
  total_cheques numeric,
  total_credito numeric,
  total_pendiente numeric,
  valores_cobrados numeric,
  valores_no_cobrados numeric,
  total_cierre numeric,
  cerrado_en timestamptz
)
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_empresa_id integer;
  v_sucursal_id smallint;
  v_usuario_id integer;
  v_empresa_nombre text;
  v_empresa_rnc text;
  v_sucursal_nombre text;
  v_cajero_nombre text;
  v_cierre_id bigint;
  v_cantidad integer;
  v_efectivo numeric(14, 2);
  v_tarjetas numeric(14, 2);
  v_depositos numeric(14, 2);
  v_cheques numeric(14, 2) := 0;
  v_credito numeric(14, 2);
  v_pendiente numeric(14, 2) := 0;
  v_cobrados numeric(14, 2);
  v_no_cobrados numeric(14, 2);
  v_total numeric(14, 2);
begin
  if nullif(trim(p_factura_desde), '') is null or nullif(trim(p_factura_hasta), '') is null then
    raise exception 'Indique el rango de facturas para el cierre.' using errcode = '22023';
  end if;

  select u.codusuario, u.empresa_id, u.sucursal_id, u.nombre_completo,
    e.nombre_comercial, e.rnc, s.nombresucursal
  into v_usuario_id, v_empresa_id, v_sucursal_id, v_cajero_nombre,
    v_empresa_nombre, v_empresa_rnc, v_sucursal_nombre
  from myappdb.usuarios u
  join myappdb.empresas e on e.id = u.empresa_id
  join myappdb.sucursales s on s.idsucursal = u.sucursal_id and s.idempresa = u.empresa_id
  where u.auth_usuario_id = (select auth.uid()) and u.estado = 'Activo';

  if not found then
    raise exception 'No se encontro un usuario activo para registrar el cierre.' using errcode = '42501';
  end if;

  select
    count(*)::integer,
    coalesce(sum(case when coalesce(forma_pago_codigo, case when condicion_pago = 'Credito' then 4 else 1 end) = 1 then total else 0 end), 0),
    coalesce(sum(case when forma_pago_codigo = 3 then total else 0 end), 0),
    coalesce(sum(case when forma_pago_codigo = 2 then total else 0 end), 0),
    coalesce(sum(case when coalesce(forma_pago_codigo, case when condicion_pago = 'Credito' then 4 else 1 end) = 4 then total else 0 end), 0),
    coalesce(sum(total), 0)
  into v_cantidad, v_efectivo, v_tarjetas, v_depositos, v_credito, v_total
  from myappdb.facturas
  where idempres = v_empresa_id
    and idsucursal = v_sucursal_id
    and estado <> 'Anulada'
    and cierre_caja_id is null
    and numero_factura >= trim(p_factura_desde)
    and numero_factura <= trim(p_factura_hasta);

  v_cobrados := v_total - v_credito;
  v_no_cobrados := v_credito + v_pendiente;

  if v_cantidad = 0 then
    raise exception 'No hay facturas pendientes dentro del rango indicado.' using errcode = 'P0001';
  end if;

  insert into myappdb.cierres_caja (
    empresa_id, empresa_nombre, empresa_rnc, sucursal_id, sucursal_nombre, usuario_id, cajero_nombre,
    factura_desde, factura_hasta, cantidad_facturas,
    total_efectivo, total_tarjetas, total_depositos, total_cheques, total_credito, total_pendiente,
    valores_cobrados, valores_no_cobrados, total_cierre, nota
  ) values (
    v_empresa_id, v_empresa_nombre, v_empresa_rnc, v_sucursal_id, v_sucursal_nombre, v_usuario_id, v_cajero_nombre,
    trim(p_factura_desde), trim(p_factura_hasta), v_cantidad,
    v_efectivo, v_tarjetas, v_depositos, v_cheques, v_credito, v_pendiente,
    v_cobrados, v_no_cobrados, v_total, nullif(trim(p_nota), '')
  ) returning cierres_caja.id into v_cierre_id;

  insert into myappdb.cierre_caja_facturas (
    cierre_caja_id, factura_id, numero_factura, fecha_factura, cliente_nombre, tipo_ncf, forma_pago_codigo, condicion_pago, cobrada_en_cierre, total
  )
  select v_cierre_id, f.id, f.numero_factura, f.fecha_factura, f.cliente_nombre, f.tipo_ncf, f.forma_pago_codigo, f.condicion_pago,
    coalesce(forma_pago_codigo, case when condicion_pago = 'Credito' then 4 else 1 end) <> 4, total
  from myappdb.facturas f
  where f.idempres = v_empresa_id
    and f.idsucursal = v_sucursal_id
    and f.estado <> 'Anulada'
    and f.cierre_caja_id is null
    and f.numero_factura >= trim(p_factura_desde)
    and f.numero_factura <= trim(p_factura_hasta);

  update myappdb.facturas
  set cierre_caja_id = v_cierre_id,
      numero_cierre = v_cierre_id
  where idempres = v_empresa_id
    and idsucursal = v_sucursal_id
    and cierre_caja_id is null
    and coalesce(forma_pago_codigo, case when condicion_pago = 'Credito' then 4 else 1 end) <> 4
    and numero_factura >= trim(p_factura_desde)
    and numero_factura <= trim(p_factura_hasta);

  return query
  select c.id, c.cantidad_facturas, c.total_efectivo, c.total_tarjetas, c.total_depositos,
    c.total_cheques, c.total_credito, c.total_pendiente, c.valores_cobrados, c.valores_no_cobrados,
    c.total_cierre, c.cerrado_en
  from myappdb.cierres_caja c where c.id = v_cierre_id;
end;
$$;

revoke all on function myappdb.crear_cierre_caja(text, text, text) from public;
grant execute on function myappdb.crear_cierre_caja(text, text, text) to authenticated;

commit;
