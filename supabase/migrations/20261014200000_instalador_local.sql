begin;

-- ===========================================================================
-- Instalador local (Plataforma › Instalador local)
--
-- Genera, desde la base en la nube, el SQL completo para crear SaltorSystem
-- en un servidor local (Supabase self-hosted): esquemas myappdb y private con
-- tablas, funciones, vistas, restricciones, índices, triggers, RLS, políticas
-- y permisos, más los catálogos generales (formas de pago, tipos de NCF, …).
-- No incluye datos de ninguna empresa.
--
-- Se usa el esquema real (no las migraciones) porque el historial de
-- migraciones no reconstruye la base desde cero.
-- ===========================================================================

create or replace function private.generar_esquema_instalador()
returns text
language plpgsql
stable
security definer
set search_path = ''
as $fn$
declare
  v_schemas text[] := array['myappdb', 'private'];
  -- Catálogos generales que necesita una instalación nueva (sin empresa_id).
  v_catalogos text[] := array['myappdb.formapago', 'myappdb.tipos_ncf', 'myappdb.tipos_anulacion',
                              'myappdb.categorias_gastos', 'myappdb.isr', 'myappdb.plataforma_planes'];
  v_out text := '';
  r record;
  v_cols text;
  v_json text;
begin
  v_out := v_out || format(E'-- SaltorSystem: esquema para instalación local\n-- Generado: %s\n\n', now())
    || E'set check_function_bodies = off;\nset client_min_messages = warning;\n'
    || E'create extension if not exists pgcrypto with schema extensions;\n'
    || E'create extension if not exists "uuid-ossp" with schema extensions;\n\n';

  -- 1) Esquemas y sus permisos ------------------------------------------------
  for r in select n.oid, n.nspname, n.nspowner, n.nspacl from pg_namespace n
           where n.nspname = any (v_schemas) order by n.nspname loop
    v_out := v_out || format(E'create schema if not exists %I;\n', r.nspname);
    v_out := v_out || coalesce((
      select string_agg(format(E'grant %s on schema %I to %s;\n', a.privilege_type, r.nspname,
               case when a.grantee = 0 then 'public' else quote_ident(pg_get_userbyid(a.grantee)) end), '')
      from aclexplode(r.nspacl) a where a.grantee <> r.nspowner), '');
  end loop;

  -- 2) Secuencias sueltas (las de columnas identity se crean con la tabla) ---
  v_out := v_out || E'\n-- Secuencias\n';
  for r in select n.nspname, c.relname, s.* from pg_class c
           join pg_namespace n on n.oid = c.relnamespace
           join pg_sequence s on s.seqrelid = c.oid
           where c.relkind = 'S' and n.nspname = any (v_schemas)
             and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'i')
           order by 1, 2 loop
    v_out := v_out || format(E'create sequence if not exists %I.%I as %s increment by %s minvalue %s maxvalue %s start with %s cache %s%s;\n',
      r.nspname, r.relname, format_type(r.seqtypid, null), r.seqincrement, r.seqmin, r.seqmax, r.seqstart, r.seqcache,
      case when r.seqcycle then ' cycle' else '' end);
  end loop;

  -- 3) Tablas (columnas; los valores por defecto van después de las funciones)
  v_out := v_out || E'\n-- Tablas\n';
  for r in select c.oid, n.nspname, c.relname from pg_class c join pg_namespace n on n.oid = c.relnamespace
           where c.relkind in ('r', 'p') and n.nspname = any (v_schemas) order by 2, 3 loop
    select string_agg(format('  %I %s%s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
             case when a.attcollation <> 0 and a.attcollation <> t.typcollation
                  then ' collate ' || (select quote_ident(cn.nspname) || '.' || quote_ident(co.collname)
                                       from pg_collation co join pg_namespace cn on cn.oid = co.collnamespace where co.oid = a.attcollation)
                  else '' end,
             case when a.attidentity = '' then ''
                  else case a.attidentity when 'a' then ' generated always' else ' generated by default' end
                       || coalesce(' as identity (sequence name ' || (
                            select quote_ident(sn.nspname) || '.' || quote_ident(sc.relname)
                            from pg_depend dp join pg_class sc on sc.oid = dp.objid join pg_namespace sn on sn.oid = sc.relnamespace
                            where dp.refobjid = a.attrelid and dp.refobjsubid = a.attnum and dp.deptype = 'i' and sc.relkind = 'S'
                            limit 1) || ')', ' as identity') end,
             case when a.attgenerated = 's' then ' generated always as (' || pg_get_expr(ad.adbin, ad.adrelid) || ') stored'
                  when a.attnotnull then ' not null' else '' end), E',\n' order by a.attnum)
      into v_cols
      from pg_attribute a
      join pg_type t on t.oid = a.atttypid
      left join pg_attrdef ad on ad.adrelid = a.attrelid and ad.adnum = a.attnum
      where a.attrelid = r.oid and a.attnum > 0 and not a.attisdropped;
    v_out := v_out || format(E'create table if not exists %I.%I (\n%s\n);\n', r.nspname, r.relname, coalesce(v_cols, ''));
  end loop;

  -- 4) Funciones ----------------------------------------------------------------
  v_out := v_out || E'\n-- Funciones\n';
  for r in select p.oid from pg_proc p join pg_namespace n on n.oid = p.pronamespace
           where n.nspname = any (v_schemas) and p.prokind in ('f', 'p')
             and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
           order by n.nspname, p.proname, p.oid loop
    v_out := v_out || pg_get_functiondef(r.oid) || E';\n\n';
  end loop;

  -- 5) Valores por defecto -------------------------------------------------------
  v_out := v_out || E'-- Valores por defecto\n';
  for r in select n.nspname, c.relname, a.attname, pg_get_expr(ad.adbin, ad.adrelid) expr
           from pg_attrdef ad
           join pg_attribute a on a.attrelid = ad.adrelid and a.attnum = ad.adnum
           join pg_class c on c.oid = ad.adrelid join pg_namespace n on n.oid = c.relnamespace
           where n.nspname = any (v_schemas) and c.relkind in ('r', 'p') and a.attgenerated = '' and not a.attisdropped
           order by 1, 2, a.attnum loop
    v_out := v_out || format(E'alter table only %I.%I alter column %I set default %s;\n', r.nspname, r.relname, r.attname, r.expr);
  end loop;

  -- 6) Vistas --------------------------------------------------------------------
  v_out := v_out || E'\n-- Vistas\n';
  for r in select c.oid, n.nspname, c.relname, c.reloptions from pg_class c join pg_namespace n on n.oid = c.relnamespace
           where c.relkind = 'v' and n.nspname = any (v_schemas) order by c.oid loop
    v_out := v_out || format(E'create or replace view %I.%I%s as\n%s;\n\n', r.nspname, r.relname,
      case when r.reloptions is null then '' else ' with (' || array_to_string(r.reloptions, ', ') || ')' end,
      rtrim(rtrim(pg_get_viewdef(r.oid, true)), ';'));
  end loop;

  -- 7) Restricciones (primero llaves, únicas y checks; luego llaves foráneas) ---
  v_out := v_out || E'-- Restricciones\n';
  for r in select n.nspname, c.relname, k.conname, pg_get_constraintdef(k.oid, true) def
           from pg_constraint k join pg_class c on c.oid = k.conrelid join pg_namespace n on n.oid = c.relnamespace
           where n.nspname = any (v_schemas) and c.relkind in ('r', 'p') and k.contype in ('p', 'u', 'x', 'c', 'f')
             and k.conislocal
           order by case when k.contype = 'f' then 1 else 0 end, 1, 2, 3 loop
    v_out := v_out || format(E'alter table only %I.%I add constraint %I %s;\n', r.nspname, r.relname, r.conname, r.def);
  end loop;

  -- 8) Índices que no vienen de una restricción --------------------------------
  v_out := v_out || E'\n-- Índices\n';
  for r in select pg_get_indexdef(i.indexrelid) def from pg_index i
           join pg_class c on c.oid = i.indrelid join pg_namespace n on n.oid = c.relnamespace
           join pg_class ic on ic.oid = i.indexrelid
           where n.nspname = any (v_schemas) and c.relkind in ('r', 'p')
             and not exists (select 1 from pg_constraint k where k.conindid = i.indexrelid and k.contype in ('p', 'u', 'x'))
           order by n.nspname, c.relname, ic.relname loop
    v_out := v_out || r.def || E';\n';
  end loop;

  -- 9) Triggers ------------------------------------------------------------------
  v_out := v_out || E'\n-- Triggers\n';
  for r in select t.oid, t.tgenabled, n.nspname, c.relname, t.tgname from pg_trigger t
           join pg_class c on c.oid = t.tgrelid join pg_namespace n on n.oid = c.relnamespace
           where n.nspname = any (v_schemas) and not t.tgisinternal order by 3, 4, 5 loop
    v_out := v_out || pg_get_triggerdef(r.oid, true) || E';\n';
    if r.tgenabled = 'D' then
      v_out := v_out || format(E'alter table %I.%I disable trigger %I;\n', r.nspname, r.relname, r.tgname);
    end if;
  end loop;

  -- 10) Seguridad por fila y políticas ----------------------------------------------
  v_out := v_out || E'\n-- Seguridad por fila\n';
  for r in select n.nspname, c.relname, c.relforcerowsecurity from pg_class c join pg_namespace n on n.oid = c.relnamespace
           where n.nspname = any (v_schemas) and c.relkind in ('r', 'p') and c.relrowsecurity order by 1, 2 loop
    v_out := v_out || format(E'alter table %I.%I enable row level security;\n', r.nspname, r.relname);
    if r.relforcerowsecurity then
      v_out := v_out || format(E'alter table %I.%I force row level security;\n', r.nspname, r.relname);
    end if;
  end loop;
  for r in select n.nspname, c.relname, p.* from pg_policy p
           join pg_class c on c.oid = p.polrelid join pg_namespace n on n.oid = c.relnamespace
           where n.nspname = any (v_schemas) order by 1, 2, p.polname loop
    v_out := v_out || format(E'create policy %I on %I.%I as %s for %s to %s%s%s;\n',
      r.polname, r.nspname, r.relname,
      case when r.polpermissive then 'permissive' else 'restrictive' end,
      case r.polcmd when 'r' then 'select' when 'a' then 'insert' when 'w' then 'update' when 'd' then 'delete' else 'all' end,
      (select string_agg(case when x = 0 then 'public' else quote_ident(pg_get_userbyid(x)) end, ', ') from unnest(r.polroles) x),
      case when r.polqual is null then '' else ' using (' || pg_get_expr(r.polqual, r.polrelid) || ')' end,
      case when r.polwithcheck is null then '' else ' with check (' || pg_get_expr(r.polwithcheck, r.polrelid) || ')' end);
  end loop;

  -- 11) Permisos de tablas, vistas, secuencias, columnas y funciones ------------
  v_out := v_out || E'\n-- Permisos\n';
  for r in select c.oid, n.nspname, c.relname, c.relkind, c.relowner, c.relacl from pg_class c
           join pg_namespace n on n.oid = c.relnamespace
           where n.nspname = any (v_schemas) and c.relkind in ('r', 'p', 'v', 'S') order by 2, 3 loop
    v_out := v_out || format(E'revoke all on %s %I.%I from public, anon, authenticated, service_role;\n',
      case when r.relkind = 'S' then 'sequence' else 'table' end, r.nspname, r.relname);
    v_out := v_out || coalesce((
      select string_agg(format(E'grant %s on %s %I.%I to %s%s;\n', a.privilege_type,
               case when r.relkind = 'S' then 'sequence' else 'table' end, r.nspname, r.relname,
               case when a.grantee = 0 then 'public' else quote_ident(pg_get_userbyid(a.grantee)) end,
               case when a.is_grantable then ' with grant option' else '' end), '' order by a.grantee, a.privilege_type)
      from aclexplode(r.relacl) a where a.grantee <> r.relowner), '');
    v_out := v_out || coalesce((
      select string_agg(format(E'grant %s (%I) on table %I.%I to %s;\n', a.privilege_type, att.attname, r.nspname, r.relname,
               case when a.grantee = 0 then 'public' else quote_ident(pg_get_userbyid(a.grantee)) end), '' order by att.attnum, a.grantee, a.privilege_type)
      from pg_attribute att, aclexplode(att.attacl) a
      where att.attrelid = r.oid and att.attacl is not null and att.attnum > 0 and not att.attisdropped), '');
  end loop;
  for r in select p.oid, n.nspname, p.proname, p.proowner, p.proacl, pg_get_function_identity_arguments(p.oid) args
           from pg_proc p join pg_namespace n on n.oid = p.pronamespace
           where n.nspname = any (v_schemas) and p.prokind in ('f', 'p') and p.proacl is not null
             and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
           order by 2, 3, 1 loop
    v_out := v_out || format(E'revoke all on function %I.%I(%s) from public, anon, authenticated, service_role;\n', r.nspname, r.proname, r.args);
    v_out := v_out || coalesce((
      select string_agg(format(E'grant execute on function %I.%I(%s) to %s;\n', r.nspname, r.proname, r.args,
               case when a.grantee = 0 then 'public' else quote_ident(pg_get_userbyid(a.grantee)) end), '' order by a.grantee)
      from aclexplode(r.proacl) a where a.grantee <> r.proowner), '');
  end loop;

  -- 12) Comentarios ----------------------------------------------------------------
  v_out := v_out || E'\n-- Comentarios\n';
  v_out := v_out || coalesce((
    select string_agg(
      case when d.classoid = 'pg_class'::regclass and d.objsubid = 0 then
             format(E'comment on %s %I.%I is %L;\n', case when c.relkind = 'v' then 'view' else 'table' end, n.nspname, c.relname, d.description)
           when d.classoid = 'pg_class'::regclass then
             format(E'comment on column %I.%I.%I is %L;\n', n.nspname, c.relname,
                    (select attname from pg_attribute where attrelid = c.oid and attnum = d.objsubid), d.description)
      end, '' order by n.nspname, c.relname, d.objsubid)
    from pg_description d join pg_class c on c.oid = d.objoid join pg_namespace n on n.oid = c.relnamespace
    where d.classoid = 'pg_class'::regclass and n.nspname = any (v_schemas) and c.relkind in ('r', 'p', 'v')), '');
  v_out := v_out || coalesce((
    select string_agg(format(E'comment on function %I.%I(%s) is %L;\n', n.nspname, p.proname,
             pg_get_function_identity_arguments(p.oid), d.description), '' order by n.nspname, p.proname)
    from pg_description d join pg_proc p on p.oid = d.objoid join pg_namespace n on n.oid = p.pronamespace
    where d.classoid = 'pg_proc'::regclass and n.nspname = any (v_schemas)), '');

  -- 13) Catálogos generales ----------------------------------------------------------
  v_out := v_out || E'\n-- Catálogos generales\n';
  for r in select c.oid, n.nspname, c.relname from pg_class c join pg_namespace n on n.oid = c.relnamespace
           where (n.nspname || '.' || c.relname) = any (v_catalogos) and c.relkind in ('r', 'p') order by 2, 3 loop
    execute format('select jsonb_agg(to_jsonb(t))::text from %I.%I t', r.nspname, r.relname) into v_json;
    continue when v_json is null;
    select string_agg(quote_ident(a.attname), ', ' order by a.attnum) into v_cols
      from pg_attribute a where a.attrelid = r.oid and a.attnum > 0 and not a.attisdropped and a.attgenerated = '';
    v_out := v_out
      || format(E'alter table %I.%I disable trigger user;\n', r.nspname, r.relname)
      || format(E'insert into %I.%I (%s) overriding system value\n  select %s from jsonb_populate_recordset(null::%I.%I, %L)\n  on conflict do nothing;\n',
                r.nspname, r.relname, v_cols, v_cols, r.nspname, r.relname, v_json)
      || format(E'alter table %I.%I enable trigger user;\n', r.nspname, r.relname);
    v_out := v_out || coalesce((
      select string_agg(format(E'select setval(pg_get_serial_sequence(%L, %L), coalesce((select max(%I) from %I.%I), 0) + 1, false);\n',
               quote_ident(r.nspname) || '.' || quote_ident(r.relname), a.attname, a.attname, r.nspname, r.relname), '')
      from pg_attribute a where a.attrelid = r.oid and a.attidentity <> ''), '');
  end loop;

  v_out := v_out || E'\nnotify pgrst, ''reload schema'';\n';
  return v_out;
end;
$fn$;

revoke all on function private.generar_esquema_instalador() from public, anon, authenticated;
grant execute on function private.generar_esquema_instalador() to service_role;

-- Para la pantalla Plataforma › Instalador local: solo los dueños del sistema.
create or replace function myappdb.plataforma_esquema_instalador()
returns text
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if not private.es_dueno_sistema() then
    raise exception 'Solo los dueños del sistema pueden generar el instalador.' using errcode = '42501';
  end if;
  return private.generar_esquema_instalador();
end;
$$;

revoke all on function myappdb.plataforma_esquema_instalador() from public, anon;
grant execute on function myappdb.plataforma_esquema_instalador() to authenticated;

commit;
