-- Módulos contratados por empresa y órdenes de venta.
-- Las órdenes son documentos comerciales internos: no consumen NCF ni se envían a DGII.

create table if not exists myappdb.empresa_modulos (
  empresa_id integer not null references myappdb.empresas(id) on delete cascade,
  modulo text not null check (modulo in (
    'mantenimiento', 'facturacion', 'cotizacion', 'caja', 'contabilidad',
    'reportes', 'configuracion', 'transacciones'
  )),
  activo boolean not null default true,
  actualizado_en timestamptz not null default now(),
  primary key (empresa_id, modulo)
);

alter table myappdb.empresa_modulos enable row level security;
revoke all on myappdb.empresa_modulos from anon, authenticated;
grant select on myappdb.empresa_modulos to authenticated;
grant insert, update, delete on myappdb.empresa_modulos to authenticated;

drop policy if exists empresa_modulos_lectura on myappdb.empresa_modulos;
create policy empresa_modulos_lectura on myappdb.empresa_modulos
  for select to authenticated
  using (
    empresa_id = (select private.current_empresa_id())
    or (select private.es_dueno_sistema())
  );

drop policy if exists empresa_modulos_dueno on myappdb.empresa_modulos;
create policy empresa_modulos_dueno on myappdb.empresa_modulos
  for all to authenticated
  using ((select private.es_dueno_sistema()))
  with check ((select private.es_dueno_sistema()));

-- Las empresas existentes conservan el acceso a los módulos que ya utilizaban.
insert into myappdb.empresa_modulos (empresa_id, modulo, activo)
select e.id, m.modulo, true
from myappdb.empresas e
cross join (values
  ('mantenimiento'), ('facturacion'), ('cotizacion'), ('caja'),
  ('contabilidad'), ('reportes'), ('configuracion')
) as m(modulo)
on conflict (empresa_id, modulo) do nothing;

create or replace function private.tg_empresa_modulos_iniciales()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  insert into myappdb.empresa_modulos (empresa_id, modulo, activo)
  values
    (new.id, 'mantenimiento', true),
    (new.id, 'facturacion', true),
    (new.id, 'cotizacion', true),
    (new.id, 'caja', true),
    (new.id, 'contabilidad', true),
    (new.id, 'reportes', true),
    (new.id, 'configuracion', true)
  on conflict (empresa_id, modulo) do nothing;
  return new;
end;
$$;

drop trigger if exists empresas_modulos_iniciales on myappdb.empresas;
create trigger empresas_modulos_iniciales
  after insert on myappdb.empresas
  for each row execute function private.tg_empresa_modulos_iniciales();

create sequence if not exists myappdb.ordenventa_numero_seq;

create table if not exists myappdb.ordenventa (
  id bigint generated by default as identity primary key,
  numero_orden text not null unique default ('OV-' || lpad(nextval('myappdb.ordenventa_numero_seq')::text, 8, '0')),
  cliente_id integer references myappdb.clients(id) on delete set null,
  cliente_nombre text not null,
  cliente_rnc text,
  cliente_telefono text,
  cliente_correo text,
  cliente_direccion text,
  cliente_ciudad text,
  fecha_orden date not null default current_date,
  condicion_pago text not null default 'Contado' check (condicion_pago in ('Contado', 'Credito')),
  forma_pago_codigo smallint,
  notas text,
  subtotal numeric(14,2) not null default 0,
  itbis numeric(14,2) not null default 0,
  total numeric(14,2) not null default 0,
  estado text not null default 'Abierta' check (estado in ('Abierta', 'Cerrada', 'Anulada')),
  idempres integer not null references myappdb.empresas(id),
  idsucursal bigint references myappdb.sucursales(idsucursal),
  usuario_id integer references myappdb.usuarios(codusuario) on delete set null,
  usuario_nombre text,
  impreso_en timestamptz,
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now()
);

create table if not exists myappdb.ordenventa_detalle (
  id bigint generated by default as identity primary key,
  ordenventa_id bigint not null references myappdb.ordenventa(id) on delete cascade,
  producto_id integer references myappdb.products(id) on delete set null,
  codigo_producto text,
  descripcion text not null,
  cantidad numeric(14,3) not null check (cantidad > 0),
  precio_unitario numeric(14,2) not null check (precio_unitario >= 0),
  tasa_itbis numeric(7,4) not null default 0,
  monto_itbis numeric(14,2) not null default 0,
  total_linea numeric(14,2) not null default 0,
  creado_en timestamptz not null default now()
);

create index if not exists ordenventa_empresa_fecha_idx on myappdb.ordenventa (idempres, fecha_orden desc, id desc);
create index if not exists ordenventa_sucursal_idx on myappdb.ordenventa (idsucursal);
create index if not exists ordenventa_detalle_orden_idx on myappdb.ordenventa_detalle (ordenventa_id);

alter table myappdb.ordenventa enable row level security;
alter table myappdb.ordenventa_detalle enable row level security;
revoke all on myappdb.ordenventa, myappdb.ordenventa_detalle from anon, authenticated;
grant select, insert, update, delete on myappdb.ordenventa, myappdb.ordenventa_detalle to authenticated;
grant usage, select on sequence myappdb.ordenventa_numero_seq to authenticated;

drop policy if exists ordenventa_tenant_access on myappdb.ordenventa;
create policy ordenventa_tenant_access on myappdb.ordenventa
  for all to authenticated
  using (idempres = (select private.current_empresa_id()))
  with check (idempres = (select private.current_empresa_id()));

drop policy if exists ordenventa_detalle_tenant_access on myappdb.ordenventa_detalle;
create policy ordenventa_detalle_tenant_access on myappdb.ordenventa_detalle
  for all to authenticated
  using (exists (
    select 1 from myappdb.ordenventa o
    where o.id = ordenventa_id
      and o.idempres = (select private.current_empresa_id())
  ))
  with check (exists (
    select 1 from myappdb.ordenventa o
    where o.id = ordenventa_id
      and o.idempres = (select private.current_empresa_id())
  ));

create or replace function myappdb.crear_orden_venta(p_orden jsonb, p_detalles jsonb)
returns table(id bigint, numero_orden text)
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_empresa integer := private.current_empresa_id();
  v_sucursal smallint := private.current_sucursal_id();
  v_usuario integer;
  v_usuario_nombre text;
  v_orden_id bigint;
  v_numero text;
begin
  if v_empresa is null then
    raise exception 'No se encontró una empresa activa.' using errcode = '42501';
  end if;
  if jsonb_typeof(p_detalles) <> 'array' or jsonb_array_length(p_detalles) = 0 then
    raise exception 'Agrega al menos un producto a la orden de venta.' using errcode = '22023';
  end if;

  select u.codusuario, u.nombre_completo
    into v_usuario, v_usuario_nombre
  from myappdb.usuarios u
  where u.auth_usuario_id = (select auth.uid())
    and u.empresa_id = v_empresa
    and u.estado = 'Activo';

  insert into myappdb.ordenventa (
    cliente_id, cliente_nombre, cliente_rnc, cliente_telefono, cliente_correo,
    cliente_direccion, cliente_ciudad, fecha_orden, condicion_pago,
    forma_pago_codigo, notas, subtotal, itbis, total, idempres, idsucursal,
    usuario_id, usuario_nombre
  ) values (
    nullif(p_orden ->> 'customerId', '')::integer,
    coalesce(nullif(trim(p_orden ->> 'customerName'), ''), 'Cliente contado'),
    nullif(trim(p_orden ->> 'rnc'), ''),
    nullif(trim(p_orden ->> 'customerPhone'), ''),
    nullif(trim(p_orden ->> 'customerEmail'), ''),
    nullif(trim(p_orden ->> 'customerAddress'), ''),
    nullif(trim(p_orden ->> 'customerCity'), ''),
    coalesce(nullif(p_orden ->> 'invoiceDate', '')::date, current_date),
    case when p_orden ->> 'paymentMethod' = 'Credito' then 'Credito' else 'Contado' end,
    nullif(p_orden ->> 'paymentMethodCode', '')::smallint,
    nullif(trim(p_orden ->> 'notes'), ''),
    coalesce((p_orden ->> 'subtotal')::numeric, 0),
    coalesce((p_orden ->> 'taxTotal')::numeric, 0),
    coalesce((p_orden ->> 'grandTotal')::numeric, 0),
    v_empresa, v_sucursal, v_usuario, v_usuario_nombre
  ) returning ordenventa.id, ordenventa.numero_orden into v_orden_id, v_numero;

  insert into myappdb.ordenventa_detalle (
    ordenventa_id, producto_id, codigo_producto, descripcion, cantidad,
    precio_unitario, tasa_itbis, monto_itbis, total_linea
  )
  select
    v_orden_id,
    nullif(item ->> 'productId', '')::integer,
    nullif(trim(item ->> 'productCode'), ''),
    coalesce(nullif(trim(item ->> 'description'), ''), 'Producto'),
    coalesce((item ->> 'quantity')::numeric, 0),
    coalesce((item ->> 'unitPrice')::numeric, 0),
    coalesce((item ->> 'taxRate')::numeric, 0),
    coalesce((item ->> 'taxAmount')::numeric, 0),
    coalesce((item ->> 'lineTotal')::numeric, 0)
  from jsonb_array_elements(p_detalles) as item;

  return query select v_orden_id, v_numero;
end;
$$;

revoke all on function myappdb.crear_orden_venta(jsonb, jsonb) from public, anon;
grant execute on function myappdb.crear_orden_venta(jsonb, jsonb) to authenticated;
