begin;

-- ===========================================================================
-- Kardex (movimientos de inventario) y ajustes.
--
-- Cada cambio de products.existencia queda registrado por un disparador con
-- tipo, cantidad, existencia antes/después, costo, documento y usuario.  El
-- tipo y el documento los aportan las funciones que mueven inventario:
--   * tipo  -> parámetro de sesión saltor.mov_tipo (set_config dentro de cada función)
--   * ref   -> saltor.mov_ref (id de la factura o de la entrada)
--   * nota  -> saltor.mov_nota (motivo del ajuste)
-- Un cambio sin origen conocido queda como "Cambio manual".
-- ===========================================================================

create table if not exists myappdb.movimientos_inventario (
  id bigint generated by default as identity primary key,
  empresa_id integer not null references myappdb.empresas(id) on delete restrict,
  producto_id integer not null references myappdb.products(id) on delete cascade,
  fecha timestamptz not null default now(),
  tipo text not null,
  cantidad numeric(14,2) not null,
  existencia_anterior numeric(14,2) not null,
  existencia_nueva numeric(14,2) not null,
  costo_unitario numeric(14,2),
  referencia_id bigint,
  documento text,
  notas text,
  usuario_nombre text,
  transaccion bigint not null default txid_current()
);

create index if not exists movimientos_inventario_producto_fecha_idx on myappdb.movimientos_inventario (producto_id, fecha);
create index if not exists movimientos_inventario_empresa_fecha_idx on myappdb.movimientos_inventario (empresa_id, fecha desc);
create index if not exists movimientos_inventario_sin_ref_idx on myappdb.movimientos_inventario (transaccion) where referencia_id is null;

alter table myappdb.movimientos_inventario enable row level security;
drop policy if exists movimientos_inventario_tenant_select on myappdb.movimientos_inventario;
create policy movimientos_inventario_tenant_select on myappdb.movimientos_inventario for select to authenticated
  using (empresa_id = (select private.current_empresa_id()));
revoke all on myappdb.movimientos_inventario from anon, authenticated;
grant select on myappdb.movimientos_inventario to authenticated;
grant all on myappdb.movimientos_inventario to service_role;

-- ---------------------------------------------------------------------------
-- Disparador que registra los movimientos
-- ---------------------------------------------------------------------------
create or replace function private.tg_products_kardex()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_tipo text := coalesce(nullif(current_setting('saltor.mov_tipo', true), ''), 'Cambio manual');
  v_ref bigint := nullif(current_setting('saltor.mov_ref', true), '')::bigint;
  v_doc text := nullif(current_setting('saltor.mov_doc', true), '');
  v_nota text := nullif(current_setting('saltor.mov_nota', true), '');
  v_usuario text;
  v_anterior numeric := case when tg_op = 'INSERT' then 0 else coalesce(old.existencia, 0) end;
  v_nueva numeric := coalesce(new.existencia, 0);
begin
  if v_anterior = v_nueva then
    return null;
  end if;
  if tg_op = 'INSERT' then
    v_tipo := 'Saldo inicial';
    v_ref := null;
  end if;

  if v_doc is null and v_ref is not null then
    if v_tipo in ('Venta', 'Edición de factura', 'Factura anulada') then
      select f.numero_factura into v_doc from myappdb.facturas f where f.id = v_ref;
    elsif v_tipo in ('Entrada de producto', 'Edición de entrada', 'Entrada eliminada') then
      select h.codigo into v_doc from myappdb.product_entry_headers h where h.id = v_ref;
    end if;
  end if;

  select u.nombre_completo into v_usuario from myappdb.usuarios u where u.auth_usuario_id = (select auth.uid());

  insert into myappdb.movimientos_inventario (
    empresa_id, producto_id, tipo, cantidad, existencia_anterior, existencia_nueva,
    costo_unitario, referencia_id, documento, notas, usuario_nombre
  ) values (
    new.empresa_id, new.id, v_tipo, v_nueva - v_anterior, v_anterior, v_nueva,
    new.costo, v_ref, v_doc, v_nota, v_usuario
  );
  return null;
end;
$$;
revoke all on function private.tg_products_kardex() from public, anon, authenticated;

drop trigger if exists products_kardex on myappdb.products;
create trigger products_kardex
  after insert or update of existencia on myappdb.products
  for each row execute function private.tg_products_kardex();

-- crear_factura conoce el número al final: etiqueta los movimientos de su transacción.
create or replace function private.etiquetar_movimientos_factura(p_factura_id bigint, p_numero text)
returns void
language sql
security definer
set search_path = ''
as $$
  update myappdb.movimientos_inventario
  set referencia_id = p_factura_id, documento = p_numero
  where transaccion = txid_current() and referencia_id is null and tipo = 'Venta';
$$;
revoke all on function private.etiquetar_movimientos_factura(bigint, text) from public, anon;
grant execute on function private.etiquetar_movimientos_factura(bigint, text) to authenticated, service_role;

-- ---------------------------------------------------------------------------
-- Las funciones que mueven inventario indican el tipo y la referencia del
-- movimiento (set_config local a la transacción, al inicio del cuerpo).
-- ---------------------------------------------------------------------------
do $$
declare
  c record;
  v_oid oid;
  v_def text;
  v_ins text;
begin
  for c in
    select * from (values
      ('crear_factura',                'Venta',              null::text),
      ('actualizar_factura',           'Edición de factura', 'p_factura_id'),
      ('anular_factura',               'Factura anulada',    'p_factura_id'),
      ('crear_entrada_productos',      'Entrada de producto', null),
      ('actualizar_entrada_productos', 'Edición de entrada', 'p_entrada_id'),
      ('eliminar_entrada_productos',   'Entrada eliminada',  'p_entrada_id'),
      ('eliminar_entrada_producto',    'Entrada eliminada',  null),
      ('registrar_entrada_producto',   'Entrada de producto', null),
      ('guardar_lineas_entrada',       null,                 'p_entrada_id')
    ) as t(fn, tipo, ref)
  loop
    for v_oid in
      select p.oid from pg_proc p join pg_namespace n on n.oid = p.pronamespace
      where n.nspname = 'myappdb' and p.proname = c.fn
    loop
      v_def := pg_get_functiondef(v_oid);
      continue when position('saltor.mov_' in v_def) > 0;
      v_ins := coalesce('  perform set_config(''saltor.mov_tipo'', ' || quote_literal(c.tipo) || ', true);' || chr(10), '')
            || coalesce('  perform set_config(''saltor.mov_ref'', ' || c.ref || '::text, true);' || chr(10), '');
      -- Primera palabra "begin" del cuerpo (sin bandera g: solo la primera).
      v_def := regexp_replace(v_def, '\mbegin\M', 'begin' || chr(10) || v_ins);
      execute v_def;
    end loop;
  end loop;

  select pg_get_functiondef(p.oid) into v_def
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'myappdb' and p.proname = 'crear_factura';
  if position('etiquetar_movimientos_factura' in v_def) = 0 then
    if position('return query select nueva_factura_id, nuevo_numero_factura;' in v_def) = 0 then
      raise exception 'crear_factura: no se encontró el punto para etiquetar los movimientos';
    end if;
    v_def := replace(v_def, 'return query select nueva_factura_id, nuevo_numero_factura;',
      'perform private.etiquetar_movimientos_factura(nueva_factura_id, nuevo_numero_factura);' || chr(10) ||
      '  return query select nueva_factura_id, nuevo_numero_factura;');
    execute v_def;
  end if;
end;
$$;

-- ---------------------------------------------------------------------------
-- Ajustes de inventario (solo administrador)
--   p_modo: 'entrada' (suma), 'salida' (resta) o 'conteo' (fija la existencia)
-- ---------------------------------------------------------------------------
create or replace function myappdb.ajustar_inventario(p_producto_id integer, p_modo text, p_cantidad numeric, p_motivo text)
returns numeric
language plpgsql
set search_path = ''
as $$
declare
  v_empresa_id integer := private.current_empresa_id();
  v_modo text := lower(trim(coalesce(p_modo, '')));
  v_actual numeric;
  v_nueva numeric;
begin
  if not private.current_user_is_admin() then
    raise exception 'Solo un administrador puede ajustar el inventario.' using errcode = '42501';
  end if;
  if nullif(trim(p_motivo), '') is null then
    raise exception 'Indique el motivo del ajuste.' using errcode = '22023';
  end if;
  if v_modo not in ('entrada', 'salida', 'conteo') then
    raise exception 'Tipo de ajuste no válido.' using errcode = '22023';
  end if;
  if p_cantidad is null or p_cantidad < 0 or (v_modo <> 'conteo' and p_cantidad = 0) then
    raise exception 'Indique una cantidad válida.' using errcode = '22023';
  end if;

  select p.existencia into v_actual
  from myappdb.products p
  where p.id = p_producto_id and p.empresa_id = v_empresa_id
  for update;
  if not found then
    raise exception 'El producto no pertenece a su empresa.' using errcode = '42501';
  end if;
  v_actual := coalesce(v_actual, 0);

  v_nueva := case v_modo
    when 'entrada' then v_actual + p_cantidad
    when 'salida' then v_actual - p_cantidad
    else p_cantidad
  end;
  if v_nueva = v_actual then
    raise exception 'La existencia no cambia con este ajuste.' using errcode = '22023';
  end if;

  perform set_config('saltor.mov_tipo', case v_modo when 'entrada' then 'Ajuste de entrada' when 'salida' then 'Ajuste de salida' else 'Ajuste por conteo' end, true);
  perform set_config('saltor.mov_nota', trim(p_motivo), true);
  perform set_config('saltor.mov_doc', 'AJUSTE', true);

  update myappdb.products p
  set existencia = v_nueva,
      estado = case
        when v_nueva <= 0 and p.estado = 'Activo' then 'Agotado'
        when v_nueva > 0 and p.estado = 'Agotado' then 'Activo'
        else p.estado end
  where p.id = p_producto_id;

  return v_nueva;
end;
$$;

revoke all on function myappdb.ajustar_inventario(integer, text, numeric, text) from public, anon;
grant execute on function myappdb.ajustar_inventario(integer, text, numeric, text) to authenticated, service_role;

-- ---------------------------------------------------------------------------
-- Saldo inicial: el kardex arranca con la existencia actual de cada producto.
-- ---------------------------------------------------------------------------
insert into myappdb.movimientos_inventario (empresa_id, producto_id, tipo, cantidad, existencia_anterior, existencia_nueva, costo_unitario, notas)
select p.empresa_id, p.id, 'Saldo inicial', coalesce(p.existencia, 0), 0, coalesce(p.existencia, 0), p.costo, 'Existencia al iniciar el kardex'
from myappdb.products p
where not exists (select 1 from myappdb.movimientos_inventario m where m.producto_id = p.id);

commit;
